/**
  * @brief This function handles USART3 global interrupt.
  */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */

  /*
   * USART3 IDLE 线检测中断处理
   *
   * 此函数在中断服务程序（ISR）上下文中被调用，因此：
   * 1. 不能做耗时操作或阻塞调用
   * 2. 不能使用 printf（printf 通过 HAL_UART_Transmit 阻塞发送）
   *
   * IDLE 中断在 USART3 总线空闲一个字符时间后触发，表示一帧数据接收完成。
   * LORA_Buf_IdleHandler() 内部会：
   * - 检查 DMA CNDTR 寄存器判断是否有新数据到达（排除初始化时的假 IDLE 中断）
   * - 记录帧描述符（起始地址 + 长度）到环形帧队列
   * - 重启 DMA Normal 模式接收下一帧
   * 必须在 HAL_UART_IRQHandler() 之前调用，因为 HAL 的处理会清除 IDLE 标志
   */
  LORA_Buf_IdleHandler();
  /* USER CODE END USART3_IRQn 0 */
  HAL_UART_IRQHandler(&huart3);
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

